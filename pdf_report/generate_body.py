def bind_headings(flowables):
    """Wrap each heading (or run of consecutive headings) with the first
    substantial flowable that follows it, so headings can never be orphaned
    at the bottom of a page."""
    out = []
    i = 0
    n = len(flowables)
    while i < n:
        el = flowables[i]
        if not hasattr(el, 'bookmark_name'):
            out.append(el)
            i += 1
            continue
        group = [el]
        j = i + 1
        # absorb consecutive headings
        while j < n and hasattr(flowables[j], 'bookmark_name'):
            group.append(flowables[j])
            j += 1
        # absorb spacing/page-break flowables up to the first substantial one
        while j < n and isinstance(flowables[j], (Spacer, CondPageBreak)):
            group.append(flowables[j])
            j += 1
        if j < n:
            group.append(flowables[j])
            j += 1
        total = 0
        for g in group:
            _, h = g.wrap(AVAIL_W, PAGE_H)
            total += h
        if total <= MAX_KEEP:
            out.append(KeepTogether(group))
        else:
            out.extend(group)
        i = j
    return out


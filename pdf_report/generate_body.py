def data_table(headers, rows, ratios, zebra=True):
    widths = [r * AVAIL_W for r in ratios]
    data = [[Paragraph(f'<b>{x}</b>', tbl_head) for x in headers]]
    for r in rows:
        data.append([Paragraph(str(c), tbl_cell) if i != 0 else Paragraph(str(c), tbl_cell)
                     for i, c in enumerate(r)])
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), ACCENT),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    if zebra:
        for i in range(1, len(data)):
            style.append(('BACKGROUND', (0, i), (-1, i),
                          colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    return t

